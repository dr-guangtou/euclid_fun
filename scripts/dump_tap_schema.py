"""Dump the Euclid Science Archive TAP_SCHEMA (tables and columns) for the DR1 schema.

Writes CSV tables plus one markdown file per TAP table into kb/data_model/tap/, so the
column-level data model is greppable and indexed by kb_search.
"""

import argparse
from pathlib import Path

from astropy.table import Table
from astroquery.esa.euclid import Euclid

project_root = Path(__file__).resolve().parents[1]


def run_query(query: str) -> Table:
    job = Euclid.launch_job_async(query, verbose=False)
    return job.get_results()


def to_text(value) -> str:
    if value is None or (hasattr(value, "mask") and value.mask):
        return ""
    text = value.decode() if isinstance(value, bytes) else str(value)
    return " ".join(text.split()).replace("|", "\\|")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schemas", nargs="+", default=["dr1", "ivoa"])
    parser.add_argument("--output_dir", default=str(project_root / "kb" / "data_model" / "tap"))
    arguments = parser.parse_args()

    output_dir = Path(arguments.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    schema_list = ", ".join(f"'{name}'" for name in arguments.schemas)
    schemas = run_query("SELECT schema_name, description FROM tap_schema.schemas")
    schemas.write(output_dir / "all_schemas.csv", overwrite=True)

    all_tables = run_query("SELECT schema_name, table_name, table_type, description FROM tap_schema.tables")
    all_tables.write(output_dir / "all_tables.csv", overwrite=True)

    tables = all_tables[[to_text(name) in arguments.schemas for name in all_tables["schema_name"]]]
    columns = run_query(
        "SELECT t.schema_name, c.table_name, c.column_name, c.datatype, c.unit, c.ucd, c.description, "
        "c.indexed, c.principal "
        "FROM tap_schema.columns AS c JOIN tap_schema.tables AS t ON c.table_name = t.table_name "
        f"WHERE t.schema_name IN ({schema_list})"
    )
    columns.write(output_dir / "selected_columns.csv", overwrite=True)

    summary_lines = [
        "# Euclid Science Archive TAP tables (" + ", ".join(arguments.schemas) + ")",
        "",
        "Generated by `scripts/dump_tap_schema.py` from `tap_schema` of https://eas.esac.esa.int/tap-server/tap.",
        "",
        "| Table | Columns | Description |",
        "|---|---|---|",
    ]
    for row in tables:
        table_name = to_text(row["table_name"])
        table_columns = columns[[to_text(name) == table_name for name in columns["table_name"]]]
        summary_lines.append(
            f"| [`{table_name}`]({table_name}.md) | {len(table_columns)} | {to_text(row['description'])[:200]} |"
        )
        table_lines = [
            f"# TAP table `{table_name}`",
            "",
            to_text(row["description"]),
            "",
            "| Column | Type | Unit | UCD | Indexed | Description |",
            "|---|---|---|---|---|---|",
        ]
        for column in table_columns:
            table_lines.append(
                f"| `{to_text(column['column_name'])}` | {to_text(column['datatype'])} | {to_text(column['unit'])} "
                f"| {to_text(column['ucd'])} | {to_text(column['indexed'])} | {to_text(column['description'])} |"
            )
        (output_dir / f"{table_name}.md").write_text("\n".join(table_lines) + "\n")
    (output_dir / "README.md").write_text("\n".join(summary_lines) + "\n")
    print(f"{len(tables)} tables, {len(columns)} columns written to {output_dir}")


if __name__ == "__main__":
    main()
